report_paw3311_t paw3311_read_burst(void) {
    report_paw3311_t report = {0};

    uint8_t motion = paw3311_read(0x02);
    if ((motion & MSB1) == MSB1) {
        // Motion detected
        uint8_t dx_l = paw3311_read(0x03);
        uint8_t dx_h = paw3311_read(0x04);
        uint8_t dy_l = paw3311_read(0x05);
        uint8_t dy_h = paw3311_read(0x06);

        report.dx = convert_twoscomp_16(dx_h, dx_l);
        report.dy = convert_twoscomp_16(dy_h, dy_l);
    }

    return report;
}

