void paw3311_set_cpi(uint16_t cpi) {
    uint8_t cpival = CONSTRAIN((cpi / PAW3311_CPI_STEP), (PAW3311_CPI_MIN / PAW3311_CPI_STEP), (PAW3311_CPI_MAX / PAW3311_CPI_STEP)) - 1U;

    paw3311_write(0x4D, 0x50);
    paw3311_write(0x4E, paw3311_cpi_lut[cpival]);
}

uint16_t paw3311_get_cpi(void) {
    uint8_t cpival = paw3311_read(0x4E);

    for (uint8_t cpi = 0; cpi < 200; cpi++) {
        if (paw3311_cpi_lut[cpi] == cpival) {
            return (cpi + 1) * PAW3311_CPI_STEP;
        }
    }

    return 0;
}

report_mouse_t paw3311_get_report(report_mouse_t mouse_report) {
    report_paw3311_t data = paw3311_read_burst();

    if (data.dx != 0 || data.dy != 0) {
//        pd_dprintf("Raw ] X: %d, Y: %d\n", data.dx, data.dy);
        mouse_report.x = CONSTRAIN_HID_XY(data.dx);
        mouse_report.y = CONSTRAIN_HID_XY(data.dy);
    }

    return mouse_report;
}

bool paw3311_check_signature(void) {
    uint8_t checkval_1 = paw3311_read(0x00);
    uint8_t checkval_2 = paw3311_read(0x5F);

    return (checkval_1 == 0x50 && checkval_2 == 0xB1);
}
